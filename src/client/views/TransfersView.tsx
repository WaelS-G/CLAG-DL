import React, { useState } from 'react';
import { DownloadTaskData, DownloadCategory } from '../../types/index.js';
import { DownloadItem } from '../components/DownloadItem';
import { SpeedGraph } from '../components/SpeedGraph';
import { Search, Filter, DownloadCloud, Plus, FileText } from 'lucide-react';

interface TransfersViewProps {
  tasks: DownloadTaskData[];
  totalSpeed: number;
  selectedCategory: DownloadCategory;
  onPause: (id: string) => void;
  onResume: (id: string) => void;
  onDelete: (id: string) => void;
  onOpenFolder: (path: string, task?: DownloadTaskData) => void;
  onOpenFile: (path: string, task?: DownloadTaskData, targetType?: 'media' | 'transcript_clean' | 'transcript_timed') => void;
  onOpenAddModal: () => void;
}

export const TransfersView: React.FC<TransfersViewProps> = ({
  tasks,
  totalSpeed,
  selectedCategory,
  onPause,
  onResume,
  onDelete,
  onOpenFolder,
  onOpenFile,
  onOpenAddModal,
}) => {
  const [search, setSearch] = useState('');
  const [statusFilter, setStatusFilter] = useState<'all' | 'active' | 'completed' | 'paused'>('all');

  const filteredTasks = tasks.filter((t) => {
    if (selectedCategory !== 'all' && t.category !== selectedCategory) {
      return false;
    }

    if (statusFilter === 'active' && t.status !== 'downloading' && t.status !== 'fetching_meta' && t.status !== 'merging') {
      return false;
    }
    if (statusFilter === 'completed' && t.status !== 'completed') {
      return false;
    }
    if (statusFilter === 'paused' && t.status !== 'paused') {
      return false;
    }

    if (search.trim()) {
      const q = search.toLowerCase();
      return t.filename.toLowerCase().includes(q) || t.url.toLowerCase().includes(q);
    }

    return true;
  });

  const activeCount = tasks.filter((t) => t.status === 'downloading').length;

  const handleExportTxt = () => {
    if (tasks.length === 0) return;

    const formatBytes = (bytes: number): string => {
      if (!bytes || bytes <= 0) return '0 B';
      const k = 1024;
      const sizes = ['B', 'KB', 'MB', 'GB', 'TB'];
      const i = Math.floor(Math.log(bytes) / Math.log(k));
      return `${(bytes / Math.pow(k, i)).toFixed(2)} ${sizes[i]}`;
    };

    const formatDate = (ts?: number): string => {
      if (!ts) return 'N/A';
      return new Date(ts).toISOString().replace('T', ' ').substring(0, 19);
    };

    const totalDownloadedBytes = tasks.reduce((acc, t) => acc + (t.downloadedBytes || 0), 0);
    const completedTasks = tasks.filter((t) => t.status === 'completed').length;

    let content = '';
    content += '================================================================================\n';
    content += '                         CLAG DOWNLOADER - TRANSFERS REPORT\n';
    content += '                           Made by: Wael Sayed\n';
    content += `                    Generated: ${formatDate(Date.now())}\n`;
    content += '================================================================================\n\n';
    content += `Total Transfers:     ${tasks.length}\n`;
    content += `Completed:           ${completedTasks}\n`;
    content += `Active / Paused:     ${tasks.length - completedTasks}\n`;
    content += `Total Downloaded:    ${formatBytes(totalDownloadedBytes)}\n\n`;
    content += '================================================================================\n';
    content += '                               DOWNLOADED ITEMS\n';
    content += '================================================================================\n\n';

    tasks.forEach((task, idx) => {
      content += `[#${idx + 1}] ${task.filename}\n`;
      content += `  Status:        ${task.status.toUpperCase()} (${task.progress.toFixed(1)}%)\n`;
      content += `  Source:        ${task.source || 'Direct'}\n`;
      content += `  Quality:       ${task.qualityLabel || task.category.toUpperCase()}\n`;
      content += `  File Size:     ${task.totalBytes > 0 ? formatBytes(task.totalBytes) : formatBytes(task.downloadedBytes)}\n`;
      if (task.subtitlesTextPath) {
        content += `  Subtitles:     ${task.subtitlesTextPath}\n`;
      }
      content += `  Original URL:  ${task.originalUrl || task.url}\n`;
      content += `  Saved Path:    ${task.savePath}\n`;
      content += `  Added At:      ${formatDate(task.createdAt)}\n`;
      content += `  Completed At:  ${formatDate(task.completedAt)}\n`;
      content += '--------------------------------------------------------------------------------\n';
    });

    content += '\n[End of Report - Generated by CLAG Downloader (Made by: Wael Sayed)]\n';

    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const blobUrl = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = blobUrl;
    const nowStr = new Date().toISOString().substring(0, 10);
    a.download = `CLAG_Downloads_Export_${nowStr}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(blobUrl);
  };

  return (
    <div className="space-y-4">
      {/* Real-Time Speed Graph when downloading */}
      {activeCount > 0 && (
        <SpeedGraph currentSpeed={totalSpeed} />
      )}

      {/* Top Filter Bar */}
      <div className="flex flex-col sm:flex-row items-stretch sm:items-center justify-between gap-3">
        {/* Search */}
        <div className="relative flex-1 max-w-md">
          <Search className="w-4 h-4 absolute left-3.5 top-1/2 -translate-y-1/2 text-gray-500" />
          <input
            type="text"
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            placeholder="Search downloads by name or URL..."
            className="w-full bg-gray-900 border border-gray-800 rounded-xl pl-10 pr-4 py-2 text-xs text-gray-200 focus:outline-none focus:border-sky-500"
          />
        </div>

        {/* Action Controls */}
        <div className="flex items-center gap-2 flex-wrap">
          {tasks.length > 0 && (
            <button
              onClick={handleExportTxt}
              className="px-3 py-2 rounded-xl bg-gray-900 hover:bg-gray-800 text-gray-300 hover:text-white border border-gray-800 flex items-center gap-1.5 text-xs font-medium transition-all shadow-sm"
              title="Export all transfers to a formatted .txt report"
            >
              <FileText className="w-3.5 h-3.5 text-cyan-400" />
              <span>Export (.txt)</span>
            </button>
          )}

          {/* Status Pills */}
          <div className="flex items-center gap-1.5 p-1 bg-gray-900 rounded-xl border border-gray-800 text-xs overflow-x-auto">
            {(['all', 'active', 'completed', 'paused'] as const).map((filter) => (
              <button
                key={filter}
                onClick={() => setStatusFilter(filter)}
                className={`px-3 py-1.5 rounded-lg capitalize font-medium transition-colors whitespace-nowrap min-h-[36px] ${
                  statusFilter === filter
                    ? 'bg-sky-500 text-white shadow-sm'
                    : 'text-gray-400 hover:text-gray-200 hover:bg-gray-800/60'
                }`}
              >
                {filter}
              </button>
            ))}
          </div>
        </div>
      </div>

      {/* Task List */}
      {filteredTasks.length === 0 ? (
        <div className="glass-panel rounded-2xl p-12 text-center flex flex-col items-center justify-center space-y-4">
          <div className="w-16 h-16 rounded-2xl bg-gray-800/80 border border-gray-700 flex items-center justify-center text-cyan-400">
            <DownloadCloud className="w-8 h-8 opacity-80" />
          </div>
          <div>
            <h4 className="font-bold text-gray-200 text-base">No downloads found</h4>
            <p className="text-xs text-gray-400 max-w-xs mt-1">
              Add a URL, paste video links, or catch browser downloads with the CLAG extension.
            </p>
          </div>
          <button
            onClick={onOpenAddModal}
            className="flex items-center gap-2 px-4 py-2 rounded-xl bg-gradient-to-r from-sky-500 to-cyan-500 text-white font-medium text-xs shadow-md"
          >
            <Plus className="w-4 h-4" /> Add First Download
          </button>
        </div>
      ) : (
        <div className="space-y-3">
          {filteredTasks.map((task) => (
            <DownloadItem
              key={task.id}
              task={task}
              onPause={onPause}
              onResume={onResume}
              onDelete={onDelete}
              onOpenFolder={onOpenFolder}
              onOpenFile={onOpenFile}
            />
          ))}
        </div>
      )}
    </div>
  );
};
